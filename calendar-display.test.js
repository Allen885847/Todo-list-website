const assert = require("node:assert/strict");
const fs = require("node:fs");

const calendarHtml = fs.readFileSync("calendar.html", "utf8");
const calendarScript = fs.readFileSync("calendar.js", "utf8");
const calendarStyles = fs.readFileSync("calendar.css", "utf8");

assert.doesNotMatch(calendarHtml, />\s*Data\s*</);
assert.doesNotMatch(calendarScript, /["'`]All [Dd]ay["'`]/);
assert.doesNotMatch(calendarScript, /createSection\("Schedule"|appendGroup\("Schedule"/);
assert.match(calendarScript, /createSection\("Tasks", tasks, \[\]/);
assert.match(calendarScript, /createSection\("Events", \[\], \[\.\.\.allDayEvents, \.\.\.timedEvents\]/);
assert.match(calendarScript, /appendGroup\("Tasks", tasks, \[\]\)/);
assert.match(calendarScript, /appendGroup\("Events", \[\], \[/);
assert.match(calendarScript, /return event\.endTime \? `\$\{start\}–\$\{formatClockTime\(event\.endTime\)\}` : start;/);
assert.match(calendarScript, /function startOfMondayWeek\(date\)/);
assert.match(calendarScript, /function renderWeek\(\) \{\s*const weekStart = startOfMondayWeek\(selectedDate\);/);
assert.match(calendarScript, /function renderMonth\(\)[\s\S]*?const gridStart = startOfWeek\(first\);/);
assert.match(calendarScript, /function createTaskStack\(tasks, isoDate, context = "day"\)/);
assert.match(calendarScript, /const layerCount = Math\.min\(Math\.max\(tasks\.length - 1, 0\), 3\)/);
assert.match(calendarScript, /layer\.className = "task-stack-layer"/);
assert.match(calendarScript, /layer\.style\.setProperty\("--stack-y"/);
assert.match(calendarScript, /layer\.style\.setProperty\("--stack-inset"/);
assert.match(calendarStyles, /transform: translateY\(var\(--stack-y\)\)/);
assert.doesNotMatch(calendarScript, /fan|--fan-angle|halfFanAngle|angleStep/);
assert.doesNotMatch(calendarStyles, /--fan-angle|rotate\(/);
assert.doesNotMatch(calendarStyles, /\.task-stack-toggle[^}]*rotate\(/s);
assert.match(calendarScript, /chevron\.classList\.toggle\("up", expanded\)/);
assert.doesNotMatch(calendarScript, /chevron\.textContent/);
assert.match(calendarScript, /itemsClip\.className = "task-stack-items-clip"/);
assert.match(calendarScript, /itemsClip\.inert = !expanded/);
assert.match(calendarScript, /updateExpandedState\(!expanded\)/);
assert.match(calendarScript, /toggle\.addEventListener\("click", \(\) => \{\s*updateExpandedState\(!expanded\);\s*\}\);/);
assert.match(calendarStyles, /grid-template-rows: 0fr/);
assert.match(calendarStyles, /grid-template-rows: 1fr/);
assert.match(calendarStyles, /grid-template-rows 230ms cubic-bezier\(0\.22, 1, 0\.36, 1\)/);
assert.match(calendarStyles, /transform: translate3d\(0, -10px, 0\) scale\(0\.985\)/);
assert.match(calendarStyles, /@media \(prefers-reduced-motion: reduce\)[\s\S]*?\.task-stack-items-clip/);
assert.match(calendarScript, /label\.textContent = `\$\{tasks\.length\} \$\{tasks\.length === 1 \? "Task" : "Tasks"\}`/);
assert.match(calendarScript, /section\.append\(createTaskStack\(sectionTasks, isoDate, "day"\)\)/);
assert.match(calendarScript, /column\.append\(createTaskStack\(groupTasks, isoDate, "week"\)\)/);
assert.match(calendarScript, /groupEvents\.forEach\(\(event\) => column\.append\(createCalendarItem\("event", event\)\)\)/);
assert.match(calendarHtml, /id="task-label"/);
assert.match(calendarScript, /className = "calendar-label-badge"/);
assert.match(calendarScript, /status\.textContent = data\.completed \? "Completed" : "Past Due"/);
assert.match(calendarStyles, /\.calendar-task-badges/);
assert.match(calendarScript, /content\.append\(titleLine\);[\s\S]*content\.append\(badges\);/);
assert.match(calendarScript, /titleLine\.append\(title\)/);
assert.match(calendarScript, /content\.append\(titleLine\)/);

console.log("Calendar labels and controls passed.");
