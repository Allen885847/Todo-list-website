const assert = require('node:assert/strict');
const { create } = require('./task-timer-engine.js');
let now = 100000;
const clock = () => now;
const a = { id: 'a', task: 'History review', completed: false };
const b = { id: 'b', task: 'Physics worksheet', completed: false };
let engine = create({},clock);
engine.start(a,600000);
now += 30000;
assert.equal(engine.remaining(engine.state.timers.a),570000);
engine.pause('a');
now += 800000;
assert.equal(engine.remaining(engine.state.timers.a),570000,'Paused timers do not lose time');
engine.resume('a');
assert.equal(engine.state.timers.a.endAt,now+570000);
engine.start(b,900000);
assert.equal(engine.state.timers.a.status,'paused');
assert.equal(engine.state.timers.b.status,'running');
assert.equal(Object.values(engine.state.timers).filter(t=>t.status==='running').length,1);
const saved = JSON.parse(JSON.stringify(engine.state));
now += 200000;
engine = create(saved,clock);
assert.equal(engine.remaining(engine.state.timers.b),700000,'Refresh retains deadline accuracy');
engine.resume('a');
assert.equal(engine.state.timers.b.status,'paused');
assert.equal(engine.remaining(engine.state.timers.b),700000);
now += 24*3600000;
assert.equal(engine.tick(),true,'Sleep expires timers based on wall time');
assert.equal(engine.state.timers.a.status,'expired');
assert.equal(engine.remaining(engine.state.timers.a),0);
assert.equal(engine.tick(),false,'Repeated ticks do not re-expire a timer');
assert.equal(a.completed,false,'Expiry never completes tasks');
engine.syncTasks([{...a,completed:true},b]);
assert(!engine.state.timers.a,'Completing a task removes its timer');
engine.syncTasks([{...b,task:'Updated physics title'}]);
assert.equal(engine.state.timers.b.title,'Updated physics title');
engine.syncTasks([]);
assert.equal(Object.keys(engine.state.timers).length,0,'Deleted tasks leave no timer');
assert.equal(engine.state.selected,null);
assert.throws(()=>engine.start(a,0));
assert.throws(()=>engine.start(a,NaN));
engine.start(a,60000);
now += 60001;
engine.pause('a');
assert.equal(engine.state.timers.a.status,'expired','Pausing at expiry cannot hide the alert');
console.log('Timer checks passed: countdown accuracy, pause/resume, one running timer, refresh recovery, device sleep, repeat expiry, task completion, deletion, edits, duration validation.');
